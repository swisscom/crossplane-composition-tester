start_functions_docker_instances() {
    if on_ci; then
        echo "Running on CI/CD. Setup of the function hosts handled by the CI/CD pipeline"
        return
    fi

    # Detect macOS and advise about podman
    if [[ "$(uname)" == "Darwin" ]]; then
        echo "INFO: Running on macOS. If you encounter docker issues, consider using podman instead:"
        echo "      - Install podman: brew install podman"
        echo "      - Set up podman machine: podman machine init && podman machine start"
        echo "      - Create docker alias: alias docker=podman"
        echo ""
    fi

    # start all docker containers
    echo "Running locally. Starting the crossplane composition function hosts if needed"

    for instance in "${FUNCTION_DOCKER_INSTANCES[@]}"; do
        IFS=':' read -r container_name port image <<< "$instance"

        # check if docker instance is already running
        if [ "$($DOCKER_CMD ps -q -f name=$container_name)" ]; then
            echo "Docker instance $container_name is already running"
		else
			echo "Starting docker instance $container_name with image $image on port $port"
			# Check if container exists but is stopped
			if [ "$($DOCKER_CMD ps -aq -f name=$container_name)" ]; then
				echo "Docker instance $container_name exists but is stopped. Removing it..."
				$DOCKER_CMD rm $container_name
			fi
			$DOCKER_CMD run -d -p $port:9443 --name $container_name $image --insecure
		fi
    done
}

stop_functions_docker_instances() {
    if on_ci; then
        echo "Running on CI/CD. No cleanup needed"
        return
    fi

    if [ "$_arg_skip_functions_docker_stop" = "on" ]; then
        echo "Skipping the automatic stop of the function docker instances as per user request!"
        return
    fi

    # stop all docker containers
    echo "Running locally. Stopping the crossplane composition function hosts"

    for instance in "${FUNCTION_DOCKER_INSTANCES[@]}"; do
        IFS=':' read -r container_name port image <<< "$instance"
        # check if docker instance is already running
        if [ "$($DOCKER_CMD ps -aq -f name=$container_name)" ]; then
			echo "Stopping and deleting docker instance $container_name"
		else
			echo "Docker instance $container_name is not running"
			continue
		fi
		# stop the container and delete it
		$DOCKER_CMD rm -f $container_name
    done
}


